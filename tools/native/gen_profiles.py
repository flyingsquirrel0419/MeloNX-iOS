#!/usr/bin/env python3
"""One nxnative host for every game: the game profiles as a table chosen at run time.
nxnative builds its host for one game (make GAME=<id>): dm/games/game.py writes game_profile.h, about forty DM_GAME_* macros, from the profile's game.tsv. MeloNX's
native mode carries every supported game in one app, so this writes, from game.py's own headers of every profile:
  - game_profile.h: the same macros, each reading the selected profile (g_dm_game) at run time; a macro only some profiles define gets DM_GAME_HAS_<NAME>;
  - dm_profiles.gen.c: the table of every profile, and dm_select_game(title ID), which the app calls before the host starts;
  - native_profiles.json: each profile's title ID, name and code modules, which the app's preparation step (src/MeloNX.Native.Prep, NativePrep) and its game list read.
The four places that need a macro at compile time (a static array of the module list or of the display versions, two #ifdef) are changed by
src/MeloNX.NativeHost/patches/0002-runtime-game-profile.patch.
Usage: gen_profiles.py <nxnative checkout> <out dir>"""
import json, os, re, subprocess, sys, tempfile

ARRAYS = {   # brace-list macros: C type of one element, and how a profile's value becomes the initializer of its own array
    'DM_GAME_MODULES': 'const char *',
    'DM_GAME_DISPLAY_VERSIONS': 'dm_display_version',
}


def headers(repo):
    games = os.path.join(repo, 'dm', 'games')
    ids = [l.split('\t')[0] for l in subprocess.run([sys.executable, os.path.join(games, 'game.py'), 'list'], capture_output=True, text=True, check=True).stdout.splitlines() if l.strip()]
    out = {}
    with tempfile.TemporaryDirectory() as t:
        for gid in ids:
            h = os.path.join(t, gid + '.h')
            subprocess.run([sys.executable, os.path.join(games, 'game.py'), 'header', gid, h], check=True, capture_output=True)
            macros = {}
            for line in open(h, encoding='utf-8'):
                m = re.match(r'#define (DM_GAME_\w+) (.*)$', line.rstrip('\n'))
                if m: macros[m.group(1)] = m.group(2).strip()
            out[gid] = macros
    return out


def kind(values):
    if all(v.startswith('"') for v in values): return 'const char *'
    if all(re.fullmatch(r'-?(0x[0-9a-fA-F]+|\d+)(ull|u|ll)?', v) for v in values): return 'uint64_t' if any(v.endswith('ull') or v.startswith('0x') for v in values) else 'int64_t'
    raise SystemExit(f'[RED] cannot type the values {values[:3]}')


def main():
    repo, out = sys.argv[1], sys.argv[2]
    profiles = headers(repo)
    names = sorted({k for p in profiles.values() for k in p})
    # The host tests these with #ifdef: a profile that defines one needs patch 0002 to turn that test into DM_GAME_HAS_<NAME> first
    ifdef = {'DM_GAME_SHARED_FONT_TTF', 'DM_GAME_NVN_API_MAJOR', 'DM_GAME_NVN_API_MINOR'} & set(names)
    if ifdef: raise SystemExit(f'[RED] profiles now define {", ".join(sorted(ifdef))}, which the host tests with #ifdef: extend patches/0002-runtime-game-profile.patch')
    optional = {k for k in names if any(k not in p for p in profiles.values())}
    fields = {}
    for k in names:
        if k in ARRAYS: continue
        fields[k] = kind([p[k] for p in profiles.values() if k in p])
    f = lambda k: k[len('DM_GAME_'):].lower()

    h = ['// Generated by tools/native/gen_profiles.py from every nxnative game profile; do not edit. The selected profile (dm_select_game) answers every DM_GAME_* macro.',
         '#pragma once', '#include <stdint.h>', '', 'typedef struct { const char *build, *ver; } dm_display_version;', '', 'typedef struct {']
    for k, t in fields.items():
        h.append(f'    {t} {f(k)};')
        if k in optional: h.append(f'    int has_{f(k)};')
    h += ['    const char *const *modules;', '    const dm_display_version *display_versions;', '    int ndisplay_versions;', '} dm_game_profile;', '',
          'extern const dm_game_profile *g_dm_game;', 'int dm_select_game(const char *title_id);   // 0 when no profile has that title ID', '']
    for k in fields:
        h.append(f'#define {k} (g_dm_game->{f(k)})')
        if k in optional: h.append(f'#define DM_GAME_HAS_{k[len("DM_GAME_"):]} (g_dm_game->has_{f(k)})')
    h += ['// arrays: the patched sites read them through these', '#define DM_GAME_MODULE_LIST (g_dm_game->modules)', '#define DM_GAME_DISPLAY_VERSION_LIST (g_dm_game->display_versions)',
          '#define DM_GAME_NDISPLAY_VERSIONS (g_dm_game->ndisplay_versions)', '']
    open(os.path.join(out, 'game_profile.h'), 'w').write('\n'.join(h))

    c = ['// Generated by tools/native/gen_profiles.py from every nxnative game profile; do not edit.', '#include "game_profile.h"', '#include <string.h>', '#include <strings.h>', '']
    for gid, p in profiles.items():
        c.append(f'static const char *const mod_{gid}[] = {p["DM_GAME_MODULES"]};')
        dv = p['DM_GAME_DISPLAY_VERSIONS'].strip()
        c.append(f'static const dm_display_version dv_{gid}[] = {{{dv}}};' if dv else f'static const dm_display_version dv_{gid}[1];')
    c += ['', 'static const dm_game_profile profiles[] = {']
    for gid, p in profiles.items():
        items = []
        for k, t in fields.items():
            v = p.get(k, '0' if t != 'const char *' else 'NULL')
            items.append(f'.{f(k)} = {v}')
            if k in optional: items.append(f'.has_{f(k)} = {int(k in p)}')
        ndv = 'sizeof dv_%s / sizeof *dv_%s' % (gid, gid) if p['DM_GAME_DISPLAY_VERSIONS'].strip() else '0'
        items += [f'.modules = mod_{gid}', f'.display_versions = dv_{gid}', f'.ndisplay_versions = {ndv}']
        c.append('    { ' + ', '.join(items) + ' },')
    c += ['};', '', 'const dm_game_profile *g_dm_game = &profiles[0];', '',
          'int dm_select_game(const char *title_id) {',
          '    for (unsigned i = 0; i < sizeof profiles / sizeof *profiles; i++)',
          '        if (!strcasecmp(profiles[i].id, title_id)) { g_dm_game = &profiles[i]; return 1; }',
          '    return 0;', '}', '']
    open(os.path.join(out, 'dm_profiles.gen.c'), 'w').write('\n'.join(c))
    unq = lambda v: json.loads(v) if v.startswith('"') else v   # the header's C string literals are JSON strings too (game.py escapes " and \\)
    rows = [{'id': gid, 'name': unq(p['DM_GAME_NAME']), 'modules': re.findall(r'"([^"]*)"', p['DM_GAME_MODULES'])} for gid, p in profiles.items()]
    with open(os.path.join(out, 'native_profiles.json'), 'w', encoding='utf-8') as fh: json.dump(rows, fh, ensure_ascii=False, indent=1)
    print(f'{out}: {len(profiles)} profiles, {len(fields)} fields ({len(optional)} optional: {", ".join(sorted(optional))})')


if __name__ == '__main__':
    main()
